local function shouldCopyFromEnUS(key)
	if type(key) ~= "string" then
		return false
	end
	if key:match("^GUIDE_ADVISOR_") then
		return false
	end
	if key:match("^GUIDE_GEAR_(MAGE|DK|DH|PRIEST|PALADIN|ROGUE|SHAMAN|WARRIOR|MONK|HUNTER|DRUID|WARLOCK|EVOKER)_") then
		return false
	end
	return true
end

local pack = {}
local en = ns._mhLocales.enUS
if type(en) == "table" then
	for key, value in pairs(en) do
		if shouldCopyFromEnUS(key) and type(value) == "string" then
			pack[key] = OVERRIDES[key] or value
		end
	end
end
for key, value in pairs(OVERRIDES) do
	pack[key] = value
end

ns._mhLocales.esES = pack

