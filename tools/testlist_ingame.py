def no_emoji(s):
    # WoW's fonts have no emoji: they would show as empty boxes. Drop them (and the variation selector) for the game.
    out = []
    for ch in s:
        o = ord(ch)
        if o > 0xFFFF or 0x2600 <= o <= 0x27BF or o in (0xFE0F, 0x200D, 0x2B50, 0x2B55, 0x2705, 0x274C):
            continue
        out.append(ch)
    return re.sub(r"\s{2,}", " ", "".join(out)).strip()


def lua_str(s):
    s = no_emoji(s)
    s = s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\r", " ").replace("\n", " ")
    return "\"" + s + "\""


def write_atomic(path, text):
    with io.open(path + ".tmp", "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(path + ".tmp", path)


def build():
    sections = tp.read_open_items()
    built = datetime.datetime.now().strftime("%d-%m %H:%M")
    out = ["-- GENERATED by tools/testlist_ingame.py from docs/TESTLIJST.md. Do not edit: run it again.",
           "MHTL_DATA = {", "\tbuilt = %s," % lua_str(built), "\tsections = {"]
    n = 0
    for s in sections:
        out.append("\t\t{ title = %s, new = %s, items = {" % (lua_str(s["title"]), "true" if s["isNew"] else "false"))
        for it in s["items"]:
            n += 1
            cmds = ", ".join(lua_str(c) for c in it.get("cmds", []))
            out.append("\t\t\t{ id = %s, indent = %d, text = %s, cmds = { %s } }," % (
                lua_str(it["id"]), it["indent"], lua_str(it["text"]), cmds))
        out.append("\t\t} },")
    out += ["\t},", "}", ""]
    data = "\n".join(out)
    for t in TARGETS:
        if not os.path.isdir(t):
            print("NOT installed (no AddOns folder): %s" % t)
            continue
        dest = os.path.join(t, NAME)
        os.makedirs(dest, exist_ok=True)
        for fn in os.listdir(SRC_ADDON):
            src = os.path.join(SRC_ADDON, fn)
            if os.path.isfile(src):
                shutil.copyfile(src, os.path.join(dest, fn + ".tmp"))
                os.replace(os.path.join(dest, fn + ".tmp"), os.path.join(dest, fn))
        write_atomic(os.path.join(dest, "Data.lua"), data)
        print("installed: %s" % dest)
    print("sections %d, open items %d, newest sections %d, items with a command %d (built %s)" % (
        len(sections), n, sum(1 for s in sections if s["isNew"]),
        sum(1 for s in sections for i in s["items"] if i.get("cmds")), built))
    print("in the game: /reload (first time: restart the game, a new addon), then /mhtest")


# --- a small reader for the SavedVariables file (the game writes plain Lua tables) --------------------------------
TOKEN = re.compile(r'\s*(?:(--[^\n]*)|(\[\s*"(?:\\.|[^"\\])*"\s*\])|(\[\s*-?\d+\s*\])|("(?:\\.|[^"\\])*")|'
                   r'(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)|(true|false|nil)|([A-Za-z_][A-Za-z0-9_]*)|(.))', re.S)


def unquote(s):
    s = s[1:-1]
    return re.sub(r'\\(.)', lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def tokens(text):
    for m in TOKEN.finditer(text):
        if m.group(1):
            continue
        if m.group(2):
            yield ("key", unquote(m.group(2).strip()[1:-1].strip()))
        elif m.group(3):
            yield ("key", int(m.group(3).strip()[1:-1]))
        elif m.group(4):
            yield ("val", unquote(m.group(4)))
        elif m.group(5):
            yield ("val", float(m.group(5)) if "." in m.group(5) or "e" in m.group(5).lower() else int(m.group(5)))
        elif m.group(6):
            yield ("val", {"true": True, "false": False, "nil": None}[m.group(6)])
        elif m.group(7):
            yield ("name", m.group(7))
        elif m.group(8) and m.group(8).strip():
            yield ("sym", m.group(8))


def parse_table(tk):
    out, idx = {}, 1
    while True:
        kind, v = next(tk)
        if kind == "sym" and v == "}":
            return out
        if kind == "sym" and v == ",":
            continue
        if kind == "key":
            next(tk)  # '='
            out[v] = parse_value(tk)
        else:
            out[idx] = parse_value(tk, (kind, v))
            idx += 1


def parse_value(tk, first=None):
    kind, v = first or next(tk)
    if kind == "sym" and v == "{":
        return parse_table(tk)
    return v


def read_sv(path):
    text = io.open(path, encoding="utf-8", errors="replace").read()
    m = re.search(r"MHTestlistDB\s*=\s*\{", text)
    if not m:
        return {}
    tk = tokens(text[m.end():])
    return parse_table(tk)


def read(write):
    merged, sources = {}, []
    for g in SV_GLOBS:
        for path in glob.glob(g):
            db = read_sv(path)
            res = db.get("results") or {}
            sources.append("%s (%d results)" % (path, len(res)))
            for k, r in res.items():
                if isinstance(r, dict) and (k not in merged or (r.get("t") or 0) > (merged[k].get("t") or 0)):
                    merged[k] = r
    print("read: " + ("; ".join(sources) if sources else "NO SavedVariables file yet (Rob: /reload after ticking)"))
    items = {}
    for s in tp.read_open_items():
        for it in s["items"]:
            items[it["id"]] = (s, it)
    stamp = "Rob in het spel, " + datetime.date.today().strftime("%d-%m-%Y")
    lines = io.open(tp.SRC, encoding="utf-8").read().split("\n")
    changes, unknown = [], []
    for k, r in sorted(merged.items(), key=lambda kv: kv[1].get("t") or 0):
        if k not in items:
            unknown.append((k, r))
            continue
        s, it = items[k]
        raw = lines[it["line"]]
        cr = "\r" if raw.endswith("\r") else ""
        row = raw[:-1] if cr else raw
        note = (r.get("n") or "").strip()
        st = r.get("s")
        new = row
        if st == "ok":
            new = row.replace("- [ ]", "- [x] ✅ (%s)" % stamp, 1) + (("  — " + note) if note else "")
        elif st == "bad":
            new = row + "  ❌ %s: %s" % (stamp, note or "niet goed (geen opmerking)")
        elif note and st != "skip":
            new = row + "  📝 %s: %s" % (stamp, note)
        elif note and st == "skip":
            new = row + "  ⏭️ %s: %s" % (stamp, note)
        if new != row:
            changes.append((it["line"], row, new + cr, s["title"], st))
    by = {}
    for c in changes:
        by[c[4]] = by.get(c[4], 0) + 1
    print("goed %d, fout %d, overgeslagen %d, alleen opmerking %d; niet (meer) open in de lijst: %d" % (
        by.get("ok", 0), by.get("bad", 0), sum(1 for k, r in merged.items() if r.get("s") == "skip"),
        by.get(None, 0), len(unknown)))
    for ln, old, new, title, st in changes:
        print("\n[%s] %s  (regel %d)" % (st or "note", title[:70], ln + 1))
        print("  - " + old.strip()[:160])
        print("  + " + new.strip()[:200])
    if unknown:
        print("\nresults for items that are no longer open or changed text (not written):")
        for k, r in unknown[:30]:
            print("  %s %s: %s %s" % (k, r.get("s"), (r.get("text") or "")[:80], ("| " + r["n"]) if r.get("n") else ""))
    if write and changes:
        for ln, old, new, _, _ in changes:
            lines[ln] = new
        write_atomic(tp.SRC, "\n".join(lines))
        print("\nwritten: %d lines in %s" % (len(changes), tp.SRC))
    elif changes:
        print("\n(proefrun: niets geschreven; met --write schrijven)")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] == "read":
        read("--write" in args)
    else:
        build()
