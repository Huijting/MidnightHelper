"""Herbs and ore veins in WoW Forever: the skill each one needs -> Modules/ForeverNodeSkillData.lua (read by
Modules/ForeverLootSparkle.lua: the node glow turns red only when you really cannot gather it).

Rob, 21 Nov 2026 (via sparring), verbatim: "c dus haha" on: "MH kijkt ook naar je eigen skill. Kun je het kruid plukken,
dan blijft de ster groen, ook als je te ver weg staat. Alleen als je het echt niet kunt (geen Herbalism of te lage
skill), wordt hij rood."

Source (GEMETEN by this script): nether.wowhead.com/forever/tooltip/object/<id> -- the line "Requires Herbalism (N)" or
"Requires Mining (N)". The required skill is server data, not in the client's DB2 (GameObjects.db2 holds only
client-placed objects: 1617 and 1731 are not in it, GEMETEN 21 Nov 2026). The object entry id is field 6 of the node's
GUID, which Blizzard did not obfuscate (only the server and spawn fields).
The ids are scanned in ranges around the Classic herb and vein ids (AFGELEID ranges; an id that is not a node is
skipped). A node that is not in the list keeps the old behaviour in the game: "you have the profession" = normal colour.

Usage (front door): run forever_nodes          numbers, writes nothing
                    run forever_nodes --emit   write the data file
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gamedata as gd  # noqa: E402

OUT = os.path.join(ROOT, "Modules", "ForeverNodeSkillData.lua")
RANGES = [(1610, 1740), (2030, 2060), (2860, 2870), (3720, 3770), (19900, 19910), (73935, 73945), (103705, 103715),
          (105565, 105575), (123305, 123315), (142138, 142146), (150075, 150085), (165655, 165660), (175400, 175410),
          (176580, 176650), (177385, 177390), (180210, 180230), (181100, 181110), (181270, 181290)]
REQ = re.compile(r"Requires (Herbalism|Mining) \((\d+)\)")


def tip(i):
    url = "https://nether.wowhead.com/forever/tooltip/object/%d" % i
    data, _ = gd.fetch(url, os.path.join(gd.CACHE, "tooltip", "forever", "object", "%d.enUS.json" % i), 30 * 86400,
                       soft404=True)
    if not data:
        return None
    try:
        return json.loads(data.decode("utf-8"))
    except ValueError:
        return None


def main():
    rows = []
    for lo, hi in RANGES:
        for i in range(lo, hi + 1):
            j = tip(i)
            if not j or not j.get("name"):
                continue
            text = " ".join(gd.strip_html(j.get("tooltip")))
            m = REQ.search(text)
            if m:
                rows.append((i, "herb" if m.group(1) == "Herbalism" else "ore", int(m.group(2)), j["name"]))
    for r in rows:
        print("%7d %-4s %3d %s" % r)
    print("nodes: %d (herb %d, ore %d)" % (len(rows), sum(1 for r in rows if r[1] == "herb"),
                                          sum(1 for r in rows if r[1] == "ore")))
    ctl = [r for r in rows if r[0] == 1618 and r[2] == 1] and [r for r in rows if r[0] == 1620 and r[2] == 50]
    print("control 1618 Peacebloom = 1 and 1620 Mageroyal = 50:", bool(ctl))
    if not ctl:
        sys.exit("positive control failed; nothing written")
    if "--emit" in sys.argv:
        out = ["local _, ns = ...", "",
               "-- GENERATED by tools/forever_nodes.py --emit from Wowhead Forever object tooltips (\"Requires Herbalism (N)\").",
               "-- Do not edit by hand. [object entry id] = required skill; kind in the comment.", "",
               "if not ns.IS_FOREVER then", "\treturn", "end", "", "ns.FOREVER_NODE_SKILL = {"]
        for i, kind, need, name in rows:
            out.append("\t[%d] = %d, -- %s %s" % (i, need, kind, name.replace("\n", " ")))
        out += ["}", ""]
        with io.open(OUT + ".tmp", "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))
        os.replace(OUT + ".tmp", OUT)
        print("wrote " + OUT)


if __name__ == "__main__":
    main()
