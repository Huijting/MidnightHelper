"""Which spell ids in ForeverSpellIds.lua are NOT a rank -> Modules/ForeverRanksData.lua (read by ForeverRanks.lua).

Rob, 21 Nov 2026 (Forever, Troll Frost Mage): "Do this now" said a button casts "Comprehend Scroll Rank 1; you know Rank 5",
and the message stayed after "Put the newest rank on them". GEMETEN in the Forever DB2 (Spell.NameSubtext_lang): the five
Comprehend Scroll ids are not ranks (1296017 "Comprehension", instant; the other four have no subtext and a 5 s cast).
The same check finds 19 of the 279 multi-id spells with ids that are not "Rank N" (Polymorph Turtle/Pig, Swipe Cat,
talent copies of Execute, Flash of Light, Holy Light …). ForeverSpellIds itself stays as it is: the key block uses it to
find the rank you can cast. Only the rank ADVICE skips these ids.

Usage (front door): run forever_rank_filter          numbers, writes nothing
                    run forever_rank_filter --emit   write the data file
"""
import csv
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gamedata as gd  # noqa: E402

SRC = os.path.join(ROOT, "Modules", "ForeverSpellIds.lua")
OUT = os.path.join(ROOT, "Modules", "ForeverRanksData.lua")
RANK = re.compile(r"^Rank \d+$")


def main():
    build = gd.latest_build("wowf")
    data, _ = gd.fetch("https://wago.tools/db2/Spell/csv?build=%s" % build,
                       os.path.join(gd.CACHE, "db2", build, "Spell.enUS.csv"), None)
    sub = {int(r["ID"]): (r.get("NameSubtext_lang") or "")
           for r in csv.DictReader(io.StringIO(data.decode("utf-8-sig", "replace")))}
    src = io.open(SRC, encoding="utf-8").read()
    skip, spells = [], 0
    for name, ids in re.findall(r'\["([^"]+)"\]\s*=\s*\{([^}]*)\}', src):
        ids = [int(x) for x in re.findall(r"\d+", ids)]
        if len(ids) < 2:
            continue
        spells += 1
        for i in ids:
            if not RANK.match(sub.get(i, "")):
                skip.append((i, name, sub.get(i, "?")))
    # Positive control: Fireball rank 1 (133) is "Rank 1" and must NOT be skipped; Comprehend Scroll 1310030 must be.
    ok = sub.get(133) == "Rank 1" and any(i == 1310030 for i, _, _ in skip) and not any(i == 133 for i, _, _ in skip)
    print("build %s: %d multi-id spells, %d ids that are not 'Rank N'; control (133 kept, 1310030 skipped): %s" % (
        build, spells, len(skip), ok))
    if not ok:
        sys.exit("positive control failed; nothing written")
    if "--emit" in sys.argv:
        out = ["local _, ns = ...", "",
               "-- GENERATED by tools/forever_rank_filter.py --emit from wago DB2 Spell.NameSubtext_lang (Forever %s)." % build,
               "-- Do not edit by hand. Spell ids in ForeverSpellIds.lua that are NOT a \"Rank N\": the rank advice skips them.",
               "", "if not ns.IS_FOREVER then", "\treturn", "end", "", "ns.FOREVER_NOT_A_RANK = {"]
        for i, name, s in skip:
            out.append("\t[%d] = true, -- %s (%s)" % (i, name, s or "no subtext"))
        out += ["}", ""]
        with io.open(OUT + ".tmp", "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))
        os.replace(OUT + ".tmp", OUT)
        print("wrote " + OUT)


if __name__ == "__main__":
    main()
