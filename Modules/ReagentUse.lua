local PREFIX = "|cffffcc00Midnight Helper:|r "
local last = "none yet" -- for /mh usedfor

local function Enabled()
	return not (ns.db and ns.db.usedForTip == false)
end

local function Readable(v)
	return v ~= nil and not (issecretvalue and issecretvalue(v))
end

local USE -- [itemID] = bits, filled on first use
local function Use()
	if USE then
		return USE
	end
	USE = {}
	for id, bits in (ns.REAGENT_PACKED or ""):gmatch("(%d+):(%d+)") do
		USE[tonumber(id)] = tonumber(bits)
	end
	return USE
end

--- This character's professions from the client: [key] = { name, line }. Keys as in ns.REAGENT_LINES.
--- The skill line GetProfessionInfo returns is the profession itself (185 Cooking), also on retail: GEMETEN 4 Oct 2026
--- ("Skinning 100 100 393", ProfessionsHub.lua) and 11 Nov 2026 in Forever (129/185/164/186 via /mh usedfor).
local function MyProfessions()
	local out = {}
	if not (GetProfessions and GetProfessionInfo and ns.REAGENT_LINES) then
		return out
	end
	local byLine = {}
	for key, line in pairs(ns.REAGENT_LINES) do
		byLine[line] = key
	end
	local ok, a, b, c, d, e, f = pcall(GetProfessions)
	if not ok then
		return out
	end
	for _, idx in ipairs({ a, b, c, d, e, f }) do
		if idx then
			local okI, name, _, _, _, _, _, line = pcall(GetProfessionInfo, idx)
			local key = okI and Readable(line) and byLine[line]
			if key then
				out[key] = { name = Readable(name) and name or nil, line = line }
			end
		end
	end
	return out
end
ns.ReagentMyProfessions = MyProfessions

local function Name(key, mine)
	if mine[key] and type(mine[key].name) == "string" then
		return mine[key].name
	end
	local names = ns.REAGENT_NAMES or {}
	local loc = GetLocale and GetLocale()
	return (loc and names[loc] and names[loc][key]) or (names.enUS and names.enUS[key]) or key
end

--- The line for this item id: text, r, g, b — or nil plus why not. Exposed for the offline check.
function ns.ReagentUseText(id, mine)
	local bits = id and Use()[id]
	if not bits then
		return nil, "not an ingredient in our list"
	end
	mine = mine or MyProfessions()
	local names, have = {}, {}
	for i, key in ipairs(ns.REAGENT_ORDER or {}) do
		if math.floor(bits / 2 ^ (i - 1)) % 2 == 1 then
			local n = Name(key, mine)
			names[#names + 1] = n
			if mine[key] then
				have[#have + 1] = n
			end
		end
	end
	if #names == 0 then
		return nil, "bits " .. bits .. " match no profession"
	end
	local suffix = ""
	if #have > 0 then
		suffix = (#names == 1) and ns:L("FUSE_HAVE_IT") or ns:L("FUSE_HAVE_FMT"):format(table.concat(have, ", "))
	end
	local text = ns:L("FUSE_TIP_FMT"):format(table.concat(names, ", "), suffix)
	if #have > 0 then
		return text, 0.37, 1, 0.33
	end
	return text, 0.6, 0.6, 0.6
end

local hooked = false
if TooltipDataProcessor and TooltipDataProcessor.AddTooltipPostCall and Enum and Enum.TooltipDataType
	and Enum.TooltipDataType.Item then
	TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, function(tooltip, data)
		-- the tooltip you hover or click, not the "Currently equipped" comparison ones beside it
		if not Enabled() or not (tooltip == GameTooltip or tooltip == ItemRefTooltip) then
			return
		end
		local ok, err = pcall(function()
			local id = type(data) == "table" and data.id
			if type(id) ~= "number" or not Readable(id) then
				last = "no readable item id"
				return
			end
			local text, r, g, b = ns.ReagentUseText(id)
			if not text then
				last = ("item %d: %s"):format(id, tostring(r))
				return
			end
			last = ("item %d: shown \"%s\""):format(id, text)
			tooltip:AddLine(text, r, g, b, true)
			tooltip:Show()
		end)
		if not ok then
			last = "error: " .. tostring(err)
		end
	end)
	hooked = true
else
	last = "this client has no TooltipDataProcessor: the line cannot be added"
end

--- /mh usedfor [on|off]
function ns.UsedForSlash(arg)
	arg = (arg or ""):lower()
	if arg == "on" or arg == "off" then
		if ns.db then
			ns.db.usedForTip = (arg == "on")
		end
		print(PREFIX .. ns:L(arg == "on" and "FUSE_ON" or "FUSE_OFF"))
		return
	end
	local n = 0
	for _ in pairs(Use()) do
		n = n + 1
	end
	local have = {}
	for key, p in pairs(MyProfessions()) do
		have[#have + 1] = ("%s (line %s)"):format(key, tostring(p.line))
	end
	print(PREFIX .. ("\"used for\" tooltip line: %s (/mh usedfor on|off). Tooltip hook: %s."):format(
		Enabled() and "on" or "off", hooked and "yes" or "NO"))
	print(("  list: %d items, %s build %s. Your professions as the client reports them: %s"):format(n,
		ns.IS_FOREVER and "Forever" or "Midnight", tostring(ns.REAGENT_BUILD),
		#have > 0 and table.concat(have, ", ") or "none"))
	print("  last item you hovered: " .. last)
end
