--[[
	ForeverReagentUse.lua — WoW Forever: the tooltip says which profession an item is an ingredient for.

	Rob, 11 Nov 2026 (sparring chat "Ja, laat bouwen", here "Ja, met probe-fix"): at a vendor he doubted whether
	Stringy Wolf Meat was good for anything, and took Meaty Bat Wing for Leatherworking (it is Cooking; same icon as
	Ruined Leather Scraps). His condition: "zonder dat we onze add-on onmenselijk groot maken".

	One line, always (bags too, not only at a vendor: the doubt starts when you pick it up):
	  "MH: Used for Cooking (you have it)"                        green: you have (one of) the professions
	  "MH: Used for Tailoring, First Aid (you have First Aid)"    green
	  "MH: Used for Leatherworking"                               grey: you have none of them
	Profession names: what this character's client calls its own professions, else the name from Blizzard's SkillLine
	table for this client language (generated), else English.
	Data: Modules/ForeverReagentData.lua, generated by tools/forever_reagents.py (rule and numbers in its header). DB2
	does not know at which skill a recipe is learned, so the line never names a skill number.
	/mh usedfor [on|off]; bare prints the last decision and its reason (CLAUDE.md: a module that can stay silent needs
	a way to see that it did).
]]

if not ns.IS_FOREVER then
	return
end

local PREFIX = "|cffffcc00Midnight Helper:|r "
local last = "none yet" -- for /mh usedfor

local function Enabled()
	return not (ns.db and ns.db.foreverUsedFor == false)
end

local USE -- [itemID] = bits, filled on first use
local function Use()
	if USE then
		return USE
	end
	USE = {}
	for id, bits in (ns.FOREVER_REAGENT_PACKED or ""):gmatch("(%d+):(%d+)") do
		USE[tonumber(id)] = tonumber(bits)
	end
	return USE
end

local ENGLISH = {}
for _, p in ipairs(ns.FOREVER_PROFS or {}) do
	ENGLISH[p[1]] = p[3]
end

local function Name(key, mine)
	if mine[key] and type(mine[key].name) == "string" then
		return mine[key].name
	end
	local loc = GetLocale and GetLocale()
	local t = ns.FOREVER_REAGENT_NAMES and loc and ns.FOREVER_REAGENT_NAMES[loc]
	return (t and t[key]) or ENGLISH[key] or key
end

--- The line for this item id: text, r, g, b — or nil plus why not. Exposed for the offline check.
function ns.ForeverReagentUseText(id, mine)
	local bits = id and Use()[id]
	if not bits then
		return nil, "not an ingredient in our list"
	end
	mine = mine or (ns.ForeverMyProfessions and ns.ForeverMyProfessions()) or {}
	local names, have = {}, {}
	for i, key in ipairs(ns.FOREVER_REAGENT_ORDER or {}) do
		if math.floor(bits / 2 ^ (i - 1)) % 2 == 1 then
			local n = Name(key, mine)
			names[#names + 1] = n
			if mine[key] then
				have[#have + 1] = n
			end
		end
	end
	if #names == 0 then
		return nil, "bits " .. bits .. " match no profession"
	end
	local suffix = ""
	if #have > 0 then
		suffix = (#names == 1) and ns:L("FUSE_HAVE_IT") or ns:L("FUSE_HAVE_FMT"):format(table.concat(have, ", "))
	end
	local text = ns:L("FUSE_TIP_FMT"):format(table.concat(names, ", "), suffix)
	if #have > 0 then
		return text, 0.37, 1, 0.33
	end
	return text, 0.6, 0.6, 0.6
end

local hooked = false
if TooltipDataProcessor and TooltipDataProcessor.AddTooltipPostCall and Enum and Enum.TooltipDataType
	and Enum.TooltipDataType.Item then
	TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, function(tooltip, data)
		-- the tooltip you hover or click, not the "Currently equipped" comparison ones beside it
		if not Enabled() or not (tooltip == GameTooltip or tooltip == ItemRefTooltip) then
			return
		end
		local ok, err = pcall(function()
			local id = type(data) == "table" and data.id
			if type(id) ~= "number" or (issecretvalue and issecretvalue(id)) then
				last = "no readable item id"
				return
			end
			local text, r, g, b = ns.ForeverReagentUseText(id)
			if not text then
				last = ("item %d: %s"):format(id, tostring(r))
				return
			end
			last = ("item %d: shown \"%s\""):format(id, text)
			tooltip:AddLine(text, r, g, b, true)
			tooltip:Show()
		end)
		if not ok then
			last = "error: " .. tostring(err)
		end
	end)
	hooked = true
else
	last = "this client has no TooltipDataProcessor: the line cannot be added"
end

--- /mh usedfor [on|off]
function ns.ForeverUsedForSlash(arg)
	arg = (arg or ""):lower()
	if arg == "on" or arg == "off" then
		if ns.db then
			ns.db.foreverUsedFor = (arg == "on")
		end
		print(PREFIX .. ns:L(arg == "on" and "FUSE_ON" or "FUSE_OFF"))
		return
	end
	local n = 0
	for _ in pairs(Use()) do
		n = n + 1
	end
	local mine = ns.ForeverMyProfessions and ns.ForeverMyProfessions() or {}
	local have = {}
	for key, p in pairs(mine) do
		have[#have + 1] = ("%s (line %s)"):format(key, tostring(p.line))
	end
	print(PREFIX .. ("\"used for\" tooltip line: %s (/mh usedfor on|off). Tooltip hook: %s."):format(
		Enabled() and "on" or "off", hooked and "yes" or "NO"))
	print(("  list: %d items, Forever build %s. Your professions as the client reports them: %s"):format(n,
		tostring(ns.FOREVER_REAGENT_BUILD), #have > 0 and table.concat(have, ", ") or "none"))
	print("  last item you hovered: " .. last)
end
