function ns.ForeverSkillupSlash(arg)
	arg = (arg or ""):lower()
	if arg == "on" or arg == "off" then
		ns.db = ns.db or {}
		ns.db.skillupTip = (arg == "on")
		print(PREFIX .. ns:L(arg == "on" and "FSKILL_TIP_ON" or "FSKILL_TIP_OFF"))
		return
	end
	if arg == "source" then
		SourceProbe()
		return
	end
	if arg == "probe" then
		Parse()
		local n = 0
		for _ in pairs(REC) do
			n = n + 1
		end
		local known = 0
		for _ in pairs(KnownTable()) do
			known = known + 1
		end
		print(PREFIX .. ("skillup: %d recipes in the list (build %s), tooltip hook %s, tooltips %s."):format(n,
			tostring(ns.SKILLUP_BUILD), hooked and "yes" or "NO", Enabled() and "on" or "off"))
		print(("  known recipes stored for this character: %d. Last: %s"):format(known, last))
		if ns.ForeverRecipeSourceLast then
			local why, credit = ns.ForeverRecipeSourceLast()
			print("  where you get a recipe: " .. why)
			print("  that data " .. credit)
		end
		print("  profession window: " .. scanWhy)
		print("  professions you do not have: " .. pruneWhy)
		local b = ns.db and ns.db.foreverKnownRecipesBackup
		print("  copy of the lists from before the repair: " .. ((type(b) == "table" and b.at)
			and ("kept (" .. (date and date("%d %b %H:%M", b.at) or b.at) .. ")") or "none"))
		local p = ns.db and ns.db.skillupProbe
		if type(p) ~= "table" then
			print("  profession window not read yet: open one (e.g. Cooking) and type /mh skillup probe again.")
			return
		end
		print("  profession window API: " .. tostring(p.api))
		for _, s in ipairs(p.samples or {}) do
			local parts = {}
			for k, v in pairs(s) do
				parts[#parts + 1] = k .. "=" .. tostring(v)
			end
			table.sort(parts)
			print("   " .. table.concat(parts, " "))
		end
		print("  (stored in MidnightHelperDB.skillupProbe after /reload)")
		return
	end
	ns.ShowForeverSkillup()
end
