local function Enabled()
	return not (ns.db and ns.db.skillupTip == false)
end

local function TipLines(tooltip, id)
	Parse()
	local spell = TEACH[id] or MADE[id]
	local mine = Mine()
	if spell and REC[spell] then
		local r = REC[spell]
		local key = ProfKey(r)
		tooltip:AddLine(ns:L("FSKILL_TIP_COLOURS_FMT"):format(ProfName(key, mine), r.y, Green(r), r.g), 0.6, 0.8, 1, true)
		local m = mine[key]
		-- A recipe you do not know: no colour for your skill. Below yellow it would read "orange, 100%", while the
		-- skill a trainer teaches it at is not in the data (offline test 20 Nov 2026: Runed Copper Breastplate at 40).
		if m and m.rank and not Knows(spell) then
			tooltip:AddLine(ns:L("FSKILL_TIP_UNKNOWN"), 0.6, 0.6, 0.6, true)
			-- 22 Nov 2026 (Rob: "1 b", "plek ja", "alles advies"): where you get the recipe (ForeverRecipeSource.lua).
			local from = ns.ForeverRecipeSourceLines and ns.ForeverRecipeSourceLines(spell)
			for i, s in ipairs(from or {}) do
				if i == 1 then
					tooltip:AddLine(s, 0.6, 0.8, 1, true)
				else
					tooltip:AddLine(s, 0.6, 0.6, 0.6, true)
				end
			end
		elseif m and m.rank then
			local c, ch = Colour(r, m.rank)
			local col = COLOUR[c]
			tooltip:AddLine(ns:L("FSKILL_TIP_YOU_FMT"):format(m.rank, ColourWord(c), math.floor(ch * 100 + 0.5)),
				col[1], col[2], col[3], true)
		end
		return ("item %d: recipe %d shown"):format(id, spell)
	end
	local used = USEDIN[id]
	if used then
		local best, bestCh
		for _, s in ipairs(used) do
			local r = REC[s]
			local m = mine[ProfKey(r)]
			if m and m.rank and Knows(s) then
				local _, ch = Colour(r, m.rank)
				if ch > 0 and (not bestCh or ch > bestCh) then
					best, bestCh = r, ch
				end
			end
		end
		if best then
			tooltip:AddLine(ns:L("FSKILL_TIP_REAGENT_FMT"):format(SpellName(best.spell), math.floor(bestCh * 100 + 0.5)),
				0.6, 0.8, 1, true)
			return ("item %d: ingredient, best recipe %d"):format(id, best.spell)
		end
		return ("item %d: ingredient, no known recipe gives a point"):format(id)
	end
	return ("item %d: not in the skill-up list"):format(id)
end

local hooked = false
if TooltipDataProcessor and TooltipDataProcessor.AddTooltipPostCall and Enum and Enum.TooltipDataType
