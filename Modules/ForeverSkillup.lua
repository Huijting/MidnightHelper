local REC, MADE, TEACH, USEDIN -- parsed on first use
local function Parse()
	if REC then
		return
	end
	REC, MADE, TEACH, USEDIN = {}, {}, {}, {}
	for entry in (ns.SKILLUP_PACKED or ""):gmatch("[^,%s]+") do
		local s, p, y, g, made, reag = entry:match("^(%d+):(%d+):(%d+):(%d+):([%d*]+):(.*)$")
		if s then
			s = tonumber(s)
			local r = { spell = s, p = tonumber(p), y = tonumber(y), g = tonumber(g), r = {} }
			local mi, mn = made:match("^(%d+)%*?(%d*)$")
			mi = tonumber(mi)
			if mi and mi > 0 then
				r.made, r.madeN = mi, tonumber(mn) or 1
				MADE[mi] = MADE[mi] or s
			end
			for part in reag:gmatch("[^/]+") do
				local id, n = part:match("^(%d+)%*?(%d*)$")
				id = tonumber(id)
				if id then
					r.r[#r.r + 1] = { id, tonumber(n) or 1 }
					local u = USEDIN[id] or {}
					u[#u + 1] = s
					USEDIN[id] = u
				end
			end
			REC[s] = r
		end
	end
	for entry in (ns.SKILLUP_ITEMS or ""):gmatch("[^,%s]+") do
		local it, s = entry:match("^(%d+):(%d+)$")
		if it then
			TEACH[tonumber(it)] = tonumber(s)
		end
	end
end

local function ProfKey(r)
	return r and ns.REAGENT_ORDER and ns.REAGENT_ORDER[r.p]
end

local function Green(r)
	return math.floor((r.y + r.g) / 2)
end

--- The colour word and the estimated chance of a point at `skill`.
local function Colour(r, skill)
	if skill < r.y then
		return "orange", 1
	elseif skill >= r.g then
		return "grey", 0
	end
	local c = (r.g - skill) / (r.g - r.y)
	return (skill >= Green(r)) and "green" or "yellow", c
end

local function Readable(v)
	return v ~= nil and not (issecretvalue and issecretvalue(v))
end

local function SpellName(id)
	if C_Spell and C_Spell.GetSpellName then
		local ok, n = pcall(C_Spell.GetSpellName, id)
		if ok and type(n) == "string" and n ~= "" and Readable(n) then
			return n
		end
	end
	if GetSpellInfo then
		local ok, n = pcall(GetSpellInfo, id)
		if ok and type(n) == "string" and n ~= "" and Readable(n) then
			return n
		end
	end
	return "#" .. tostring(id)
end

local function ItemName(id)
	if C_Item and C_Item.GetItemNameByID then
		local ok, n = pcall(C_Item.GetItemNameByID, id)
		if ok and type(n) == "string" and n ~= "" and Readable(n) then
			return n
		end
	end
	if C_Item and C_Item.RequestLoadItemDataByID then
		pcall(C_Item.RequestLoadItemDataByID, id)
	end
	return ns:L("FVEND_ITEM_LOADING")
end

local function Count(id)
	local f = (C_Item and C_Item.GetItemCount) or GetItemCount
	if not f then
		return 0
	end
	local ok, n = pcall(f, id, true) -- true = the bank too (as far as the client knows it)
	return (ok and type(n) == "number" and Readable(n)) and n or 0
end

local function ColourWord(c)
	return ns:L("FSKILL_COL_" .. c:upper())
end

