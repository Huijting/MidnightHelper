--- The text for one profession.
local function PlanText(key, mine)
	local m = mine[key]
	local name = ProfName(key, mine)
	local L = {}
	local function add(s)
		L[#L + 1] = s
	end
	add("|cffffcc66" .. name .. (m and m.rank and m.maxRank and ("  %d/%d"):format(m.rank, m.maxRank) or "") .. "|r")
	if not (m and m.rank) then
		add(ns:L("FSKILL_NOT_YOURS"))
		return table.concat(L, "\n")
	end
	if KnownCount(key) == 0 then
		add(ns:L("FSKILL_OPEN_WINDOW_FMT"):format(name))
		return table.concat(L, "\n")
	end
	local maxed = m.maxRank and m.maxRank > 0 and m.rank >= m.maxRank
	if maxed then
		add(ns:L("FSKILL_MAXED_FMT"):format(m.maxRank))
	end
	local step, list = NextStep(key, m.rank, m.maxRank)
	if not step then
		if not maxed then
			add(ns:L("FSKILL_NONE"))
		end
		return table.concat(L, "\n")
	end
	if not maxed then
		add(" ")
		add("|cff66ccff" .. ns:L("FSKILL_NEXT_FMT"):format(step.crafts, RecipeLink(step.r) .. "|cff66ccff", step.from, step.to)
			.. "|r")
		if step.nextR then
			add(ns:L("FSKILL_THEN_FMT"):format(RecipeLink(step.nextR)))
		end
	end
	add(" ")
	add("|cffffcc66" .. ns:L("FSKILL_SUREST") .. "|r")
	for i = 1, math.min(3, #list) do
		local e = list[i]
		local col = COLOUR[e.colour]
		add(("|cff%02x%02x%02x%d.|r "):format(math.floor(col[1] * 255), math.floor(col[2] * 255), math.floor(col[3] * 255), i)
			.. ns:L("FSKILL_ROW_FMT"):format(RecipeLink(e.r), ColourWord(e.colour), math.floor(e.chance * 100 + 0.5)))
	end
	if not maxed then
		add(" ")
		add("|cffffcc66" .. ns:L("FSKILL_SHOP") .. "|r")
		local all = true
		for _, rg in ipairs(step.r.r) do
			local need, have = rg[2] * step.crafts, Count(rg[1])
			local line = ns:L("FSKILL_SHOP_ROW_FMT"):format(ItemLink(rg[1]), need, have)
			local first, needs
			if have < need then
				all = false
				line = line .. "  |cffff7f7f" .. ns:L("FSKILL_SHOP_MORE_FMT"):format(need - have) .. "|r"
				first, needs = MakeFirst(key, rg[1], need - have)
			else
				line = line .. "  |cff40ff40" .. ns:L("FSKILL_SHOP_OK") .. "|r"
			end
			add("  " .. line)
			if first then
				add("     |cff66ccff" .. first .. "|r")
				add("          " .. needs)
			end
		end
		if all then
			add("  " .. ns:L("FSKILL_SHOP_DONE"))
		end
	end
	add(" ")
	add("|cff9d9d9d" .. ns:L("FSKILL_ESTIMATE") .. "|r")
	return table.concat(L, "\n")
end

ns.ForeverSkillupPlanText = PlanText -- for the offline check (scratch test), like ns.ReagentUseText

Fill = function()
	local f = Build()
	f.title:SetText(ns:L("FSKILL_TITLE"))
	local mine = Mine()
	local keys = {}
	for _, k in ipairs(ns.REAGENT_ORDER or {}) do
		if mine[k] then
			keys[#keys + 1] = k
		end
	end
	local found = false
	for _, k in ipairs(keys) do
		if k == selected then
			found = true
		end
	end
	if not found then
		selected = keys[1]
	end
	for i, b in ipairs(f.profBtns) do
		local k = keys[i]
		if k then
			b.key = k
			b:SetText(ProfName(k, mine))
			if k == selected then
				b:LockHighlight()
			else
				b:UnlockHighlight()
			end
			b:Show()
		else
			b:Hide()
		end
	end
	if not selected then
		f.text:SetText(ns:L("FSKILL_EMPTY"))
		f.go:Hide()
	else
		f.text:SetText(PlanText(selected, mine))
		f.go:SetText(ns:L("FSKILL_GO_TRAINER"))
		f.go:Show()
	end
	f.child:SetHeight(math.max(10, (f.text:GetStringHeight() or 0) + 8))
	if f.lastSelected ~= selected then
		f.offset, f.lastSelected = 0, selected
	end
	f.ApplyScroll()
end

--- Open the window, optionally on one profession key (the Professions page passes its own).
function ns.ShowForeverSkillup(key)
	local f = Build()
	if key and IsCrafting(key) then
		selected = key
	end
	if f:IsShown() then
		Fill()
	else
		f:Show()
	end
end

