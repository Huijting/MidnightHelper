--- Your known recipes of this profession that still give a point at `skill`, surest first:
--- { { r, colour, chance, have = true/false } … }.
local function Surest(key, skill)
	Parse()
	local out = {}
	for s, r in pairs(REC) do
		if ProfKey(r) == key and Knows(s) then
			local c, ch = Colour(r, skill)
			if ch > 0 then
				local have = true
				for _, rg in ipairs(r.r) do
					if Count(rg[1]) < rg[2] then
						have = false
					end
				end
				out[#out + 1] = { r = r, colour = c, chance = ch, have = have }
			end
		end
	end
	table.sort(out, function(a, b)
		if math.abs(a.chance - b.chance) > 0.001 then
			return a.chance > b.chance
		end
		if a.have ~= b.have then
			return a.have
		end
		if a.r.g ~= b.r.g then
			return a.r.g < b.r.g
		end
		return a.r.spell < b.r.spell
	end)
	return out
end

local function KnownCount(key)
	Parse()
	local n = 0
	for s, r in pairs(REC) do
		if ProfKey(r) == key and Knows(s) then
			n = n + 1
		end
	end
	return n
end

--- The next step: { r, crafts, from, to, nextR } — crafts = expected number (1 / chance per point, summed), rounded up.
local function NextStep(key, skill, cap)
	local list = Surest(key, skill)
	local best = list[1]
	if not best then
		return nil, list
	end
	local r = best.r
	-- At most STEP_MAX points per step (offline test 20 Nov 2026: an orange recipe gave "about 38x" in one go); after
	-- that MH works out the next step again with what you know then.
	local to = math.max(skill + 1, math.min(Green(r), skill + STEP_MAX))
	if cap and cap > 0 then
		to = math.min(to, cap)
	end
	local crafts = 0
	for s = skill, to - 1 do
		local _, ch = Colour(r, s)
		if ch <= 0 then
			to = s
			break
		end
		crafts = crafts + 1 / ch
	end
	crafts = math.max(1, math.ceil(crafts))
	local after = Surest(key, to)
	local nextR
	for _, e in ipairs(after) do
		if e.r.spell ~= r.spell then
			nextR = e.r
			break
		end
	end
	return { r = r, crafts = crafts, from = skill, to = to, nextR = nextR, chance = best.chance, colour = best.colour },
		list
end

local function Mine()
	return ns.ForeverMyProfessions and ns.ForeverMyProfessions() or {}
end

local function IsCrafting(key)
	for _, k in ipairs(ns.REAGENT_ORDER or {}) do
		if k == key then
			return true
		end
	end
	return false
end

local function ProfName(key, mine)
	return ns.ForeverProfName and ns.ForeverProfName(key, mine) or key
end

--- One line for the Professions page of the overview: "Skill up: next, about 6x Rough Sharpening Stone." or nil.
function ns.ForeverSkillupSummary(key)
	if not IsCrafting(key) then
		return nil
	end
	local m = Mine()[key]
	if not (m and m.rank) then
		return nil
	end
	if m.maxRank and m.maxRank > 0 and m.rank >= m.maxRank then
		return ns:L("FSKILL_MAXED_FMT"):format(m.maxRank)
	end
	local step = NextStep(key, m.rank, m.maxRank)
	if step then
		return ns:L("FSKILL_SUMMARY_FMT"):format(step.crafts, SpellName(step.r.spell))
	end
	return nil
end

