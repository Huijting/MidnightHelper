--- Up to three recipes you do not know, can learn at this skill and that still give a point, with where you get them.
--- Returns the lines and the first arrow row. At what skill you learn one is never shown, only used to choose.
local function LearnLines(key, skill)
	local out, pickList = {}, {}
	if not (ns.RECIPE_SOURCE and ns.ForeverRecipeSourceLines) then
		return out
	end
	for s, src in pairs(ns.RECIPE_SOURCE) do
		local r = REC[s]
		if r and src.k ~= "K" and src.at and src.at <= skill and ProfKey(r) == key and not Knows(s) then
			local _, ch = Colour(r, skill)
			if ch > 0 then
				pickList[#pickList + 1] = { r = r, ch = ch, go = ns.ForeverRecipeHasArrow(s) }
			end
		end
	end
	table.sort(pickList, function(a, b)
		if a.go ~= b.go then
			return a.go
		end
		if math.abs(a.ch - b.ch) > 0.001 then
			return a.ch > b.ch
		end
		if a.r.g ~= b.r.g then
			return a.r.g > b.r.g
		end
		return a.r.spell < b.r.spell
	end)
	local first, n = nil, 0
	for _, e in ipairs(pickList) do
		local lines, row = ns.ForeverRecipeSourceLines(e.r.spell)
		if lines then
			if n == 0 then
				out[1] = " "
				out[2] = "|cffffcc66" .. ns:L("FRSRC_HEAD") .. "|r"
			end
			out[#out + 1] = "  " .. RecipeLink(e.r)
			for i, s in ipairs(lines) do
				out[#out + 1] = "     " .. (i == 1 and "|cff99ccff" or "|cff9d9d9d") .. s .. "|r"
			end
			first = first or row
			n = n + 1
			if n == 3 then
				break
			end
		end
	end
	return out, first
end

--- The text for one profession.
local planSeller -- the seller of the first ingredient you are short of (the window's arrow button), or nil
local function PlanText(key, mine)
	planSeller = nil
	local m = mine[key]
	local name = ProfName(key, mine)
	local L = {}
	local function add(s)
		L[#L + 1] = s
	end
	add("|cffffcc66" .. name .. (m and m.rank and m.maxRank and ("  %d/%d"):format(m.rank, m.maxRank) or "") .. "|r")
	if not (m and m.rank) then
		add(ns:L("FSKILL_NOT_YOURS"))
		return table.concat(L, "\n")
	end
	if KnownCount(key) == 0 then
		add(ns:L("FSKILL_OPEN_WINDOW_FMT"):format(name))
		return table.concat(L, "\n")
	end
	local maxed = m.maxRank and m.maxRank > 0 and m.rank >= m.maxRank
	if maxed then
		add(ns:L("FSKILL_MAXED_FMT"):format(m.maxRank))
	end
	local step, list = NextStep(key, m.rank, m.maxRank)
	local learn, learnRow = LearnLines(key, m.rank)
	if not step then
		if not maxed then
			add(ns:L("FSKILL_NONE"))
		end
		for _, s in ipairs(learn) do
			add(s)
		end
		planSeller = learnRow
		return table.concat(L, "\n")
	end
	if not maxed then
		add(" ")
		add("|cff66ccff" .. ns:L("FSKILL_NEXT_FMT"):format(step.crafts, RecipeLink(step.r) .. "|cff66ccff", step.from, step.to)
			.. "|r")
		if step.nextR then
			add(ns:L("FSKILL_THEN_FMT"):format(RecipeLink(step.nextR)))
		end
	end
	add(" ")
	add("|cffffcc66" .. ns:L("FSKILL_SUREST") .. "|r")
	for i = 1, math.min(3, #list) do
		local e = list[i]
		local col = COLOUR[e.colour]
		add(("|cff%02x%02x%02x%d.|r "):format(math.floor(col[1] * 255), math.floor(col[2] * 255), math.floor(col[3] * 255), i)
			.. ns:L("FSKILL_ROW_FMT"):format(RecipeLink(e.r), ColourWord(e.colour), math.floor(e.chance * 100 + 0.5)))
	end
	if not maxed then
		add(" ")
		add("|cffffcc66" .. ns:L("FSKILL_SHOP") .. "|r")
		local all = true
		for _, rg in ipairs(step.r.r) do
			local need, have = rg[2] * step.crafts, Count(rg[1])
			local line = ns:L("FSKILL_SHOP_ROW_FMT"):format(ItemLink(rg[1]), need, have)
			local first, needs
			if have < need then
				all = false
				line = line .. "  |cffff7f7f" .. ns:L("FSKILL_SHOP_MORE_FMT"):format(need - have) .. "|r"
				first, needs = MakeFirst(key, rg[1], need - have)
			else
				line = line .. "  |cff40ff40" .. ns:L("FSKILL_SHOP_OK") .. "|r"
			end
			add("  " .. line)
			if first then
				add("     |cff66ccff" .. first .. "|r")
				add("          " .. needs)
			end
			-- 22 Nov 2026 (Rob: "plek ja"): short of it → where you get it, and the arrow button below.
			if have < need and ns.ForeverReagentSourceText then
				local from, seller = ns.ForeverReagentSourceText(rg[1])
				if from then
					add("     |cff99ccff" .. from .. "|r")
					planSeller = planSeller or seller
				end
			end
		end
		if all then
			add("  " .. ns:L("FSKILL_SHOP_DONE"))
		end
	end
	for _, s in ipairs(learn) do
		add(s)
	end
	planSeller = planSeller or learnRow -- the ingredient you are short of comes first
	add(" ")
	add("|cff9d9d9d" .. ns:L("FSKILL_ESTIMATE") .. "|r")
	return table.concat(L, "\n")
end

